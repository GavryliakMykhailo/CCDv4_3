% =========================================================================
% Назва файлу: generate_virtual_tissue.m
% Опис: Генератор синтетичних комплексних амплітуд (ex, ey) для 6 
%       базових станів поляризації. ШУМ додається до фізичних 
%       характеристик середовища (ро та сігма).
% =========================================================================

clc; clear; close all;
disp('Початок генерації віртуального поляризаційного середовища...');

% -------------------------------------------------------------------------
% 1. ОСНОВНІ НАЛАШТУВАННЯ ТА ПАРАМЕТРИ ШУМУ ТКАНИНИ
% -------------------------------------------------------------------------
M = 800;  % Кількість рядків (вісь Y)
N = 1200; % Кількість стовпців (вісь X)

% Налаштування структурного шуму тканини
add_structural_noise = true; % true - додати шум до структури, false - ідеальна тканина
noise_std_rho   = 0.2;       % Стандартне відхилення шуму для осі ро (в радіанах)
noise_std_sigma = 0.2;       % Стандартне відхилення шуму для фази сігма (в радіанах)

% Налаштування макроструктури середовища
A = pi / 4; % Максимальний кут ро (в радіанах)
B = pi;     % Максимальний фазовий зсув сігма

% Оберіть тип середовища: 'sinusoidal_2d', 'sinusoidal_1d', або 'gaussian'
tissue_type = 'sinusoidal_1d'; 

% -------------------------------------------------------------------------
% 2. Генерація ІДЕАЛЬНОГО просторового розподілу (ро та сігма)
% -------------------------------------------------------------------------
[X, Y] = meshgrid(1:N, 1:M);

switch tissue_type
    case 'sinusoidal_2d'
        period_x = N / 3; period_y = M / 2; 
        rho_ideal   = A * sin(2 * pi * X / period_x) .* cos(2 * pi * Y / period_y); 
        sigma_ideal = B * cos(2 * pi * X / period_x) .* sin(2 * pi * Y / period_y);
        
    case 'sinusoidal_1d'
        period_x = N / 3;
        rho_ideal   = A * sin(2 * pi * X / period_x); 
        sigma_ideal = B * cos(2 * pi * X / period_x);
        
    case 'gaussian'
        centerX = N / 2; centerY = M / 2; 
        wx = N / 6; wy = M / 6; 
        sigma_ideal = B * exp(-((X - centerX).^2 / (2 * wx^2) + (Y - centerY).^2 / (2 * wy^2)));
        period_x = N / 3;
        rho_ideal   = A * sin(2 * pi * X / period_x); 
end

% -------------------------------------------------------------------------
% 3. ДОДАВАННЯ СТРУКТУРНОГО ШУМУ ДО РО ТА СІГМА
% -------------------------------------------------------------------------
if add_structural_noise
    % Генеруємо дійсний гаусівський шум (randn) з заданим відхиленням
    noise_matrix_rho   = noise_std_rho * randn(M, N);
    noise_matrix_sigma = noise_std_sigma * randn(M, N);
    
    rho   = rho_ideal + noise_matrix_rho;
    sigma = sigma_ideal + noise_matrix_sigma;
    disp('Додано структурний шум до параметрів \rho та \sigma.');
else
    rho   = rho_ideal;
    sigma = sigma_ideal;
    disp('Структурний шум вимкнено (ідеальна тканина).');
end

% -------------------------------------------------------------------------
% 4. Розрахунок матриці Джонса (вже зашумленого середовища)
% -------------------------------------------------------------------------
exp_pos = exp(1i * sigma / 2);
exp_neg = exp(-1i * sigma / 2);

J11 = cos(rho).^2 .* exp_pos + sin(rho).^2 .* exp_neg;
J12 = cos(rho) .* sin(rho) .* (exp_pos - exp_neg);
J21 = J12; 
J22 = sin(rho).^2 .* exp_pos + cos(rho).^2 .* exp_neg;

% -------------------------------------------------------------------------
% 5. Генерація 6 станів поляризації (пропускаємо світло через тканину)
% -------------------------------------------------------------------------
ex_0 = J11;                           ey_0 = J21;
ex_90 = J12;                          ey_90 = J22;
ex_45 = (J11 + J12) / sqrt(2);        ey_45 = (J21 + J22) / sqrt(2);
ex_135 = (J11 - J12) / sqrt(2);       ey_135 = (J21 - J22) / sqrt(2);
ex_prav = (J11 - 1i * J12) / sqrt(2); ey_prav = (J21 - 1i * J22) / sqrt(2);
ex_liv = (J11 + 1i * J12) / sqrt(2);  ey_liv = (J21 + 1i * J22) / sqrt(2);


% -------------------------------------------------------------------------
% 6. Візуалізація параметрів середовища
% -------------------------------------------------------------------------
figure('Name', 'Синтезоване середовище (з урахуванням шуму)', 'Position', [150, 150, 1000, 400]);

subplot(1, 2, 1);
imagesc(rho); colormap(gca, 'jet'); colorbar;
% Використовуємо cell array {} для багаторядкового заголовка
title({'Орієнтація \rho (радіани)', sprintf('Шум: %.2f рад', noise_std_rho)}); 
axis image off;

subplot(1, 2, 2);
imagesc(sigma); colormap(gca, 'jet'); colorbar;
% Використовуємо cell array {} для багаторядкового заголовка
title({'Фазовий зсув \sigma (радіани)', sprintf('Шум: %.2f рад', noise_std_sigma)}); 
axis image off;